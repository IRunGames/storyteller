-- The table chat: one row per line said at a story's table, by a player or
-- the storyteller, or put there by the table itself (is_system: the divider
-- when the storyteller moves to another scene, a card untapped). The sender
-- is id_created_by_user, which the metatable procedures below add; there is
-- no id_user column for it.
--
-- id_story_scene is the scene the table was on when the line was said, so
-- the chat can open on the scene being played. It is null for a line said
-- while the session was on no scene, and set back to null if the scene is
-- ever deleted, so the line outlives it.
CREATE TABLE IF NOT EXISTS chats (
    id_chat        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_story       integer NOT NULL REFERENCES stories (id_story) ON DELETE CASCADE,
    id_story_scene integer REFERENCES story_scenes (id_story_scene) ON DELETE SET NULL,
    chat_text      text    NOT NULL,
    is_edited      boolean NOT NULL DEFAULT FALSE,
    is_system      boolean NOT NULL DEFAULT FALSE
);

-- Register the table so the needs_* flags have a row to land on. On a
-- database built from scratch _tables may be empty at this point.
CALL _p_update_tables();

-- _p_update_tables() only overwrites the has_* flags on conflict, never the
-- needs_* ones, so this survives later runs.
UPDATE _tables
SET needs_timestamps = TRUE,
    needs_user_ids   = TRUE,
    updated_at       = NOW()
WHERE table_name = 'chats';

-- A table absent from _tables would silently miss out, so say so instead.
DO
$$
    BEGIN
        IF NOT EXISTS (SELECT 1 FROM _tables WHERE table_name = 'chats') THEN
            RAISE EXCEPTION
                'chats is not present in _tables even after '
                    '_p_update_tables(), so its audit columns cannot be added.';
        END IF;
    END
$$;

-- Adds created_at / updated_at with the set_updated_at trigger, then
-- id_created_by_user / id_updated_by_user with their foreign keys. Both are
-- idempotent across every flagged table.
CALL _p_update_tables_timestamps();
CALL _p_update_tables_user_ids();

-- The chat opens on one scene's lines, newest page first, and pages back
-- through them by (created_at, id_chat). After the CALLs, since created_at is
-- theirs to add.
CREATE INDEX IF NOT EXISTS idx_chats_story_scene_created
    ON chats (id_story, id_story_scene, created_at, id_chat);

