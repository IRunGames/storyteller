-- Invitations: a link, usually also emailed, that brings someone into the app.
-- A storyteller's invitation names a story (id_story) and seats whoever
-- accepts it there; an administrator's names a user type (id_user_type) and
-- raises the account that accepts it to that type. The sender is
-- id_created_by_user, which the metatable procedures below add.
--
-- token is what the link carries (/invite/<token>). It is kept as it is, as
-- stories.join_code is, rather than hashed: an administrator copies the link
-- again from the list, which a hash would not allow.
--
-- An invitation is live until it is accepted, revoked or past expires_at.
-- Only one live invitation may name an email per story, and only one app
-- invitation per email: the two partial unique indexes keep a second one out
-- even when two sends race. An expired invitation still counts as unaccepted
-- here, so the app revokes it before inviting that email again.
CREATE TABLE IF NOT EXISTS invitations (
    id_invitation       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email               text        NOT NULL,
    token               text        NOT NULL UNIQUE,
    id_story            integer REFERENCES stories (id_story) ON DELETE CASCADE,
    id_user_type        integer REFERENCES s_user_types (id_user_type) ON UPDATE CASCADE,
    expires_at          timestamptz NOT NULL,
    accepted_at         timestamptz,
    id_accepted_by_user uuid REFERENCES s_users (id_user) ON DELETE SET NULL,
    revoked_at          timestamptz,
    CONSTRAINT invitations_story_or_type CHECK (id_story IS NOT NULL OR id_user_type IS NOT NULL)
);

CREATE UNIQUE INDEX IF NOT EXISTS invitations_live_story_email
    ON invitations (id_story, email)
    WHERE id_story IS NOT NULL AND accepted_at IS NULL AND revoked_at IS NULL;

CREATE UNIQUE INDEX IF NOT EXISTS invitations_live_app_email
    ON invitations (email)
    WHERE id_story IS NULL AND accepted_at IS NULL AND revoked_at IS NULL;

-- Registers the table in _tables, raising if it is not there afterwards,
-- then adds created_at / updated_at with the set_updated_at trigger,
-- id_created_by_user / id_updated_by_user with their foreign keys, and an
-- index on every foreign key.
CALL _p_set_and_update_table_features('invitations',
    p_timestamps := TRUE,
    p_user_ids   := TRUE);

