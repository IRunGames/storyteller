-- Feedback left from the menu bar's feedback popover, one row per submission.
-- status is the kind, set by the button picked: THUMBS_UP, THUMBS_DOWN or IDEA,
-- run by the Feedback Status Workflow (-7, seeds/seed_s_statuses.sql). The
-- submitter is id_created_by_user, which the metatable procedure below adds
-- along with created_at / updated_at, so no user column is declared here.
-- ip_address is nullable because local development has no proxy in front of
-- Next and therefore no x-forwarded-for header to read.
--
-- The table was first built with is_positive boolean in place of status;
-- migrations/20261031194320_convert_feedback_is_positive_to_status.sql made
-- the change on databases that already had it.
CREATE TABLE IF NOT EXISTS feedback (
    id_feedback integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status      varchar NOT NULL DEFAULT 'THUMBS_UP',
    page_path   text    NOT NULL,
    feedback    text,
    ip_address  text
);

-- Registers the table in _tables, raising if it is not there afterwards,
-- then adds created_at / updated_at with the set_updated_at trigger,
-- id_created_by_user / id_updated_by_user with their foreign keys, an index
-- on every foreign key, and the workflow's CHECK, <status>_at columns and
-- triggers.
CALL _p_set_and_update_table_features('feedback',
    p_timestamps          := TRUE,
    p_user_ids            := TRUE,
    p_status_workflow_ids := ARRAY[-7]);
