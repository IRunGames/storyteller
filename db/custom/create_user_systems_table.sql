-- The systems a user likes, listed on their profile under "Systems I like".
-- A table rather than a list in user_preferences so each entry points at a
-- real systems row: a system can never be liked twice by the same user, and
-- a system still liked cannot be deleted out from under the list. id_user is
-- the owner of the list and the key it is read by; it sits alongside the
-- id_created_by_user the metatable adds for the same reason it does on
-- user_preferences, because the UNIQUE constraint has to name a column this
-- file owns.
CREATE TABLE IF NOT EXISTS user_systems (
    id_user_system integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_user        uuid    NOT NULL REFERENCES s_users (id_user),
    id_system      integer NOT NULL REFERENCES systems (id_system),
    CONSTRAINT user_systems_id_user_id_system_key UNIQUE (id_user, id_system)
);

-- Register the table so the needs_* flags have a row to land on. On a
-- database built from scratch _tables may be empty at this point.
CALL _p_update_tables();

-- _p_update_tables() only overwrites the has_* flags on conflict, never the
-- needs_* ones, so this survives later runs.
UPDATE _tables
SET needs_timestamps = TRUE,
    needs_user_ids   = TRUE,
    updated_at       = NOW()
WHERE table_name = 'user_systems';

-- A table absent from _tables would silently miss out, so say so instead.
DO
$$
    BEGIN
        IF NOT EXISTS (SELECT 1 FROM _tables WHERE table_name = 'user_systems') THEN
            RAISE EXCEPTION
                'user_systems is not present in _tables even after '
                    '_p_update_tables(), so its audit columns cannot be added.';
        END IF;
    END
$$;

-- Adds created_at / updated_at with the set_updated_at trigger, then
-- id_created_by_user / id_updated_by_user with their foreign keys. Both are
-- idempotent across every flagged table.
CALL _p_update_tables_timestamps();
CALL _p_update_tables_user_ids();
