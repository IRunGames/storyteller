-- Where an attachment is used: by the story itself (its cover), by one of
-- the story's sessions or scenes, by one of its elements (the element's
-- picture), or by an element's link to one scene (scene_elements: how the
-- element looks in that scene, which its pill shows there in place of the
-- element's own picture). An attachment is a file a story owns
-- (attachments.id_story); this table is the holders that show it, any
-- number of them, so the same picture can be a scene's cover and an
-- element's at once. Before this table an attachment hung off one holder
-- through attachments.kind and attachments.external_id, and moved between
-- holders.
--
-- `kind` is NOT declared here. _p_update_tables_kinds() builds it, and the
-- attachment_uses_kind enum behind it, from the kind_values declared below.
-- external_id is the holder's primary key in whichever table kind names;
-- there is no foreign key, so tr_attachment_uses_external_exists stands in
-- for one, and tr_attachment_uses_delete_for_parent takes a holder's uses
-- down with it.
--
-- id_story is the attachment's story, copied by tr_attachment_uses_same_story
-- and held to the holder's: a story's uses, and whether the caller may touch
-- one, are then one lookup here.
--
-- tags is the standard tags feature. 'cover' marks the holder's default
-- picture, one per holder (attachment_uses_one_cover_idx); the file's own
-- tags stay on attachments.tags.
--
-- sort_order is the holder's order for its pictures. It is NOT NULL with no
-- default: tr_attachment_uses_sort_order fills a row left without one with
-- 1000 + its id, so new uses fall in after any ordered by hand.
CREATE TABLE IF NOT EXISTS attachment_uses (
    id_attachment_use integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_attachment     integer NOT NULL REFERENCES attachments (id_attachment) ON DELETE CASCADE,
    id_story          integer NOT NULL REFERENCES stories (id_story) ON DELETE CASCADE,
    external_id       integer NOT NULL,
    sort_order        integer NOT NULL
);

-- The whole _tables setup in one call: registration, the needs_* flags, the
-- audit columns and their foreign keys, the tags column, the kind column and
-- its enum, and the foreign-key indexes. It raises if the table is missing
-- from _tables afterwards.
CALL _p_set_and_update_table_features('attachment_uses',
    p_timestamps  := TRUE,
    p_user_ids    := TRUE,
    p_tags        := TRUE,
    p_kind_values := ARRAY['STORY', 'STORY_SESSION', 'STORY_SCENE', 'ELEMENT', 'SCENE_ELEMENT']);

-- _p_update_tables_kinds() adds the column nullable, as it must for a table
-- that might already hold rows. Every use has a kind from the start.
ALTER TABLE attachment_uses ALTER COLUMN kind SET NOT NULL;

-- An attachment is used by a holder once.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1
                   FROM pg_constraint
                   WHERE conname = 'attachment_uses_id_attachment_kind_external_id_key'
                     AND conrelid = 'attachment_uses'::regclass) THEN
        ALTER TABLE attachment_uses
            ADD CONSTRAINT attachment_uses_id_attachment_kind_external_id_key
                UNIQUE (id_attachment, kind, external_id);
    END IF;
END $$;

-- Written by hand because _p_update_fk_indexes only indexes real foreign
-- keys, and external_id is not one. Every read of this table is "the
-- pictures of this holder".
CREATE INDEX IF NOT EXISTS attachment_uses_kind_external_id_idx
    ON attachment_uses (kind, external_id);

-- At most one cover per holder, so "which picture is the cover" always has a
-- single answer and two storytellers' clicks cannot leave two.
CREATE UNIQUE INDEX IF NOT EXISTS attachment_uses_one_cover_idx
    ON attachment_uses (kind, external_id)
    WHERE tags @> ARRAY['cover'];
