-- Attachment annotations: the storyteller's drawing over one of the story's
-- uploaded pictures, fog of war and pen marks, one row per picture. The
-- drawing is the file's: every element that shows the file, as its own
-- picture or as its picture in a scene, gives the players the drawing.
--
-- is_active is the picture's "annotated" designation: while it is on,
-- players are given the players' copy (player_url) in place of the raw
-- picture wherever an element shows it. Turning it off keeps the drawing for
-- the next time.
--
-- ops is the drawing as an ordered list of steps (brush, rectangle, Cover
-- all / Clear all, pen mark, shape, eraser, Erase all annotations, wall, wall
-- eraser, flood), read and written through the zod schema in
-- apps/web/src/lib/annotation-schemas.ts. Its coordinates are in the
-- picture's own pixels, width by height, as measured upright. Walls are the
-- storyteller's alone and are never drawn into the players' copy.
--
-- fog_opacity_players and fog_color are how the fog is drawn in the players'
-- copy; the color is held to #rrggbb because it is written into SVG.
--
-- revision counts the saves; player_revision is the revision player_url was
-- rendered from, so a players' copy behind the drawing is told by the two
-- differing. render_token and render_claimed_at let one render at a time
-- claim the row, a claim older than a minute counting as abandoned.
CREATE TABLE IF NOT EXISTS attachment_annotations (
    id_attachment_annotation integer  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_attachment          integer     NOT NULL UNIQUE REFERENCES attachments (id_attachment) ON DELETE CASCADE,
    is_active              boolean     NOT NULL DEFAULT TRUE,
    width                  integer     NOT NULL CHECK (width > 0),
    height                 integer     NOT NULL CHECK (height > 0),
    ops                    jsonb       NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(ops) = 'array'),
    revision               integer     NOT NULL DEFAULT 0,
    fog_opacity_players    smallint    NOT NULL DEFAULT 100 CHECK (fog_opacity_players BETWEEN 0 AND 100),
    fog_color              text        NOT NULL DEFAULT '#1b1d23' CHECK (fog_color ~ '^#[0-9a-fA-F]{6}$'),
    player_url             text,
    player_revision        integer,
    render_token           uuid,
    render_claimed_at      timestamptz
);

-- Registers the table in _tables, raising if it is not there afterwards,
-- then adds created_at / updated_at with the set_updated_at trigger,
-- id_created_by_user / id_updated_by_user with their foreign keys, and an
-- index on every foreign key.
CALL _p_set_and_update_table_features('attachment_annotations',
    p_timestamps := TRUE,
    p_user_ids   := TRUE);
