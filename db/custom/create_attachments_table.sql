-- A picture (or later, any file) a story owns. Replaces the image_url /
-- image_link columns stories, sessions and scenes used to carry: one shape
-- for every file, several per story, and -- because a row exists before its
-- bytes do -- an upload that has a state rather than being an event that
-- either happened or did not.
--
-- Which of the story's parts show the file (the story's own cover, a
-- session, a scene, an element) is attachment_uses, one row per holder; see
-- create_attachment_uses_table.sql. Until that table existed the holder was
-- kind and external_id here, and the migrations that moved them are
-- attachment_uses_from_attachments and drop_attachments_kind_external_id.
--
-- id_story, tags and search_text were added by later migrations
-- (add_attachments_id_story, tag_attachment_covers,
-- add_attachments_search_text) and are not repeated here.
CREATE TABLE IF NOT EXISTS attachments (
    id_attachment integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status        varchar NOT NULL DEFAULT 'UPLOADING',
    url           text,
    -- Recorded at write time rather than re-derived from the URL, so a change
    -- of Blob domain cannot silently turn our own files into other people's.
    is_uploaded   boolean NOT NULL DEFAULT FALSE,
    file_name     text,
    content_type  varchar,
    byte_size     bigint,
    -- What makes READY mean the address exists.
    CONSTRAINT attachments_ready_has_url CHECK (status <> 'READY' OR url IS NOT NULL)
);

-- The whole _tables setup in one call: registration, the needs_* flags, the
-- audit columns and their foreign keys, activity_log, the status workflow,
-- and the foreign-key indexes. It raises if the table is missing from
-- _tables afterwards, or if workflow -3 is unseeded.
CALL _p_set_and_update_table_features('attachments',
    p_timestamps          := TRUE,
    p_user_ids            := TRUE,
    p_activity_log        := TRUE,
    p_status_workflow_ids := ARRAY[-3]);
