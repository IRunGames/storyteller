import { formatSessionLength } from "./stories";

/** Scenes per fetch in the Prep Work board's Scenes column. */
export const SCENES_PAGE_SIZE = 10;

/** How long the Scenes search box waits after a keystroke before it asks, in ms. */
export const SCENE_SEARCH_DELAY_MS = 250;

/** One card in the Scenes column. */
export type StoryScene = {
  idStoryScene: number;
  /** The sitting it was played in; null while it waits on the board. */
  idStorySession: number | null;
  /**
   * The status the row holds, as the database has it. Not narrowed to the
   * statuses the workflow lists today: those are read from s_statuses at run
   * time, so a status added to the workflow needs no change here.
   */
  status: string;
  /**
   * When the row entered the status it holds, from the <status>_at column the
   * workflow keeps for it. Null when nothing has stamped that status: a row
   * seeded straight into it, or a workflow whose trigger has not run.
   */
  statusAt: Date | null;
  /**
   * Which finished scene of its sitting this was, in the order they were
   * finished. Null until the scene is finished, so the board numbers what
   * has been played and leaves the rest unnumbered.
   */
  sceneNumber: number | null;
  /**
   * Whole minutes the scene spent in play, once it has been finished; null
   * before. Generated by the database from each stretch in active.
   */
  length: number | null;
  title: string;
  /** What the storyteller wrote: the NPCs in it and anything of note. */
  description: string | null;
  /**
   * The sitting's place in its story's opening order, the same number the
   * Timeline gives it. Null while the scene waits on the board.
   */
  sessionNumber: number | null;
  /**
   * The sitting it was played in, as the Timeline names it ("3. Kildealg"),
   * or null while the scene waits on the board. The card shows the number
   * alone and keeps this for the tooltip behind it.
   */
  sessionHeading: string | null;
};

/** What the scene info panel shows for one scene: the card's fields and the picture. */
export type StorySceneDetail = StoryScene & {
  /** The story it belongs to, whose attachments the panel can offer it. */
  idStory: number;
  imageLink: string | null;
  /**
   * When the scene went into play, from active_at; null for one that never
   * has. The workflow restamps it each time, so a scene picked up again
   * shows the latest.
   */
  startedAt: Date | null;
  /**
   * The caller is the story's storyteller rather than one of its players, so
   * the status is theirs to move and the story's attachments theirs to add.
   */
  isStoryteller: boolean;
  /**
   * The elements linked to the scene, in the play space's order. The
   * storyteller gets every one as written; a player gets only what the
   * players' table shows (see SceneElementInfo).
   */
  elements: SceneElementInfo[];
};

/**
 * One element in a scene's info panel, with its status in the scene
 * (scene_elements). For a player it is cut to what the players' table
 * shows: no INVISIBLE link at all, the name the link shows rather than the
 * true one, and the description only while the link's show_info allows it.
 * The cutting is the action's, so nothing held back reaches the browser.
 */
export type SceneElementInfo = {
  idSceneElement: number;
  kind: string;
  /** The true name for the storyteller; the name the link shows for a player. */
  label: string;
  /** The title, when there is one and the label is not already it. */
  detail: string | null;
  description: string | null;
  status: string;
};

/** One scene as a session's info panel lists it. */
export type SessionScene = {
  idStoryScene: number;
  title: string;
  status: string;
};

/**
 * The status a scene can no longer be edited in: it has been played out, so
 * what it says is the record of what happened. Named here, rather than read
 * as "the workflow's last status", because the scene workflow is a cycle and
 * has no last status the database would recognise as final; the edit action
 * checks it again.
 */
export const SCENE_LOCKED_STATUS = "COMPLETE";

/**
 * The status a scene waits in before it is played: the storyteller has not
 * opened it, or has set it back after opening it. The players' table puts up
 * a "stand by" overlay over a pending scene; the storyteller's does not, since
 * it is the storyteller who moves the scene on.
 */
export const SCENE_PENDING_STATUS = "PENDING";

/** A sitting of the story, as the scene form's select offers it. */
export type SceneSessionOption = {
  idStorySession: number;
  /** "3. Kildealg", as the Timeline names it. */
  label: string;
};

/** "45 minutes", "1 minute", or in hours from an hour up, as a session's length reads. */
export function formatSceneLength(minutes: number): string {
  if (minutes >= 60) return formatSessionLength(minutes);
  return `${minutes} ${minutes === 1 ? "minute" : "minutes"}`;
}

/**
 * A scene's description and notes, as the panel behind its title at either
 * table shows and edits them. Null for one left empty, as the columns hold
 * it.
 */
export type SceneText = { description: string | null; notes: string | null };

export const EMPTY_SCENE_TEXT: SceneText = { description: null, notes: null };

/**
 * What saving the panel hands back: the text as stored, or errors by field.
 * The live-edit page's panel renames the scene too, and has the title back.
 */
export type SetSceneTextResult =
  { ok: true; text: SceneText; title?: string } | { ok: false; errors: Record<string, string> };

/**
 * The address of a scene's preview: the scene as the players would see it,
 * with nothing to press, for the storyteller to look something up in
 * another tab without moving the table. Keyed on the scene alone, since a
 * scene names its story.
 */
export function scenePreviewPath(idStoryScene: number): string {
  return `/preview/scene/${idStoryScene}`;
}
